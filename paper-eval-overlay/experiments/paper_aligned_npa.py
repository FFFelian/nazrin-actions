# Import-time consistency checks: every Kind has a parameter sequence and every
# referenced parameter has an explicit source/mask contract.
if set(TACTIC_PARAMETERS) != set(TacticKind):
    raise RuntimeError("TACTIC_PARAMETERS must define exactly one entry per TacticKind")
for _kind, _parameters in TACTIC_PARAMETERS.items():
    if len(set(_parameters)) != len(_parameters):
        raise RuntimeError(f"duplicate parameter in sequence for {_kind.name}")
    for _parameter in _parameters:
        _spec = PARAMETER_SPECS.get(_parameter)
        if _spec is None:
            raise RuntimeError(f"missing ParameterSpec for {_parameter!r}")
        if (_parameter in POINTER_PARAMETERS) != (_spec.kind == "pointer"):
            raise RuntimeError(f"inconsistent pointer declaration for {_parameter!r}")
        if _spec.kind == "categorical" and _parameter not in CATEGORY_VALUES:
            raise RuntimeError(f"categorical parameter {_parameter!r} has no CATEGORY_VALUES")



@dataclass(frozen=True)
class ExprGraph:
    """Typed heterogeneous expression graph; node indices are graph-local.

    `constant_ids` uses -1 for non-constant nodes and unseen constants; known
    constants use IDs in [0, model.num_constants). `edge_index` is [2, E], with
    each column a directed source-to-destination edge and `edge_types` carrying
    its relation ID.
    """

    node_kinds: Tensor
    edge_index: Tensor
    edge_types: Tensor
    constant_ids: Tensor
    node_features: Tensor

    def validate(self, node_feature_dim: int) -> None:
        if self.node_kinds.ndim != 1 or self.node_kinds.dtype != torch.long:
            raise ValueError("node_kinds must be a rank-1 torch.long tensor")
        n = self.node_kinds.shape[0]
        if self.node_features.shape != (n, node_feature_dim):
            raise ValueError(f"node_features must have shape ({n}, {node_feature_dim})")
        if not self.node_features.is_floating_point():
            raise ValueError("node_features must have a floating-point dtype")
        if self.constant_ids.shape != (n,) or self.constant_ids.dtype != torch.long:
            raise ValueError("constant_ids must be a rank-1 torch.long tensor matching node count")
        if self.edge_index.ndim != 2 or self.edge_index.shape[0] != 2:
            raise ValueError("edge_index must have shape [2, E]")
        if self.edge_index.dtype != torch.long:
            raise ValueError("edge_index must have dtype torch.long")
        e = self.edge_index.shape[1]
        if self.edge_types.shape != (e,) or self.edge_types.dtype != torch.long:
            raise ValueError("edge_types must be a rank-1 torch.long tensor matching edge count")
        tensors = (self.edge_index, self.edge_types, self.node_features, self.constant_ids)
        if any(t.device != self.node_kinds.device for t in tensors):
            raise ValueError("all ExprGraph tensors must be on the same device")
        if e and (int(self.edge_index.min()) < 0 or int(self.edge_index.max()) >= n):
            raise ValueError("edge_index contains a node index outside the graph")


@dataclass(frozen=True)
class PointerCandidates:
    """Graph-local node indices and an eligibility mask for one pointer head."""

    indices: Tensor
    mask: Tensor

    def validate(self, node_count: int, device: torch.device) -> None:
        if self.indices.ndim != 1 or self.indices.dtype != torch.long:
            raise ValueError("pointer candidate indices must be rank-1 torch.long")
        if self.mask.shape != self.indices.shape or self.mask.dtype != torch.bool:
            raise ValueError("pointer candidate mask must be bool and match indices")
        if self.indices.device != device or self.mask.device != device:
            raise ValueError("pointer candidates must be on the graph device")
        if self.indices.numel():
            if int(self.indices.min()) < 0 or int(self.indices.max()) >= node_count:
                raise ValueError("pointer candidate references a node outside the graph")
            if torch.unique(self.indices).numel() != self.indices.numel():
                raise ValueError("pointer candidate node indices must be unique")


@dataclass(frozen=True)
class PremiseCandidates:
    """Global constant-vocabulary IDs and eligibility mask for premise retrieval."""

    constant_ids: Tensor
    mask: Tensor

    def validate(self, num_constants: int, device: torch.device) -> None:
        if self.constant_ids.ndim != 1 or self.constant_ids.dtype != torch.long:
            raise ValueError("premise candidate IDs must be rank-1 torch.long")
        if self.mask.shape != self.constant_ids.shape or self.mask.dtype != torch.bool:
            raise ValueError("premise candidate mask must be bool and match IDs")
        if self.constant_ids.device != device or self.mask.device != device:
            raise ValueError("premise candidates must be on the model device")
        if self.constant_ids.numel():
            if int(self.constant_ids.min()) < 0 or int(self.constant_ids.max()) >= num_constants:
                raise ValueError("premise candidate ID is outside the constant vocabulary")
            if torch.unique(self.constant_ids).numel() != self.constant_ids.numel():
                raise ValueError("premise candidate IDs must be unique")


@dataclass(frozen=True)
class CandidateSet:
    premise: PremiseCandidates
    free_variable: PointerCandidates
    locus: PointerCandidates

    def for_parameter(self, name: str) -> PointerCandidates | PremiseCandidates:
        if name not in POINTER_PARAMETERS:
            raise ValueError(f"{name!r} is not a pointer parameter")
        return getattr(self, name)


@dataclass(frozen=True)
class TacticPrefix:
    """A chosen Kind and contiguous selected parameter prefix.

    Premise values are global constant-vocabulary IDs; free-variable and locus
    values are graph-local node indices. Categorical values are class indices
    in CATEGORY_VALUES. Selected values are validated but do not condition later
    parameter logits, matching the paper's stated simplification.
    """

    kind: TacticKind
    selected: Mapping[str, int] = field(default_factory=dict)


@dataclass(frozen=True)
class FixedPointDiagnostics:
    converged: bool
    iterations: int
    residual: float
    unseen_count: int


@dataclass(frozen=True)
class NPAOutput:
    node_embeddings: Tensor
    pooled_embedding: Tensor
    kind_logits: Tensor
    next_parameter: Optional[str]
    parameter_logits: Optional[Tensor]
    decoder_state: Optional[Tensor]
    fixed_point: FixedPointDiagnostics

    @property
    def abandon_logit(self) -> Tensor:
        return self.kind_logits[int(TacticKind.ABANDON)]

    @property
    def is_complete(self) -> bool:
        """The NPA reaches Exit after all arguments, without a learned Exit action."""
        return self.decoder_state is not None and self.next_parameter is None


@dataclass(frozen=True)
class NPAPrefixOutput:
    """All Kind-dependent parameter logits for one teacher-forced prefix.

    The logits are computed from the Kind-conditioned decoder state only.  They
    do not condition on earlier selected parameter values, matching the paper's
    stated simplification and making one graph pass sufficient for supervised
    training over every parameter head.
    """

    node_embeddings: Tensor
    pooled_embedding: Tensor
    kind_logits: Tensor
    parameter_logits: Mapping[str, Tensor]
    decoder_state: Tensor
    fixed_point: FixedPointDiagnostics
    kind: TacticKind
    selected: Mapping[str, int]

    @property
    def next_parameter(self) -> Optional[str]:
        """Next parameter implied by the selected contiguous prefix, if any."""
        sequence = TACTIC_PARAMETERS[TacticKind(self.kind)]
        if len(self.selected) >= len(sequence):
            return None
        return sequence[len(self.selected)]

    @property
    def is_complete(self) -> bool:
        return self.next_parameter is None


class FixedPointConstantEncoder(nn.Module):
    """Contractive contextual embeddings for constants without vocabulary IDs.

    This update is an independent design choice, not a paper equation. It uses
    m_i(u) = mean_j(W u_j + r_ji) and u'_i = (1-a)b_i + a*tanh(b_i + m_i(u)).
    W has spectral norm at most one. In the max-over-nodes Euclidean norm,
    incoming means and tanh are non-expansive, so 0 < a < 1 makes the update a
    contraction. Known constants and other node-feature states remain fixed.
    The residual is reported in that same norm; CUDA reductions may differ by
    floating-point roundoff. This is a contextual encoder, not yet a complete
    definition-graph encoder for globally unseen constant identities.
    """

    def __init__(
        self,
        num_relations: int,
        hidden_dim: int = HIDDEN_DIM,
        damping: float = 0.5,
        tolerance: float = 1e-6,
        max_iterations: int = 128,
    ) -> None:
        super().__init__()
        if not 0.0 < damping < 1.0:
            raise ValueError("damping must be strictly between zero and one")
        if tolerance <= 0 or max_iterations < 1:
            raise ValueError("tolerance and max_iterations must be positive")
        self.hidden_dim = hidden_dim
        self.damping = damping
        self.tolerance = tolerance
        self.max_iterations = max_iterations
        self.message_weight = nn.Parameter(torch.empty(hidden_dim, hidden_dim))
        self.relation_embedding = nn.Embedding(num_relations, hidden_dim)
        nn.init.xavier_uniform_(self.message_weight)

    def forward(
        self, base: Tensor, graph: ExprGraph, unseen_mask: Tensor
    ) -> tuple[Tensor, FixedPointDiagnostics]:
        if base.ndim != 2 or base.shape != (graph.node_kinds.shape[0], self.hidden_dim):
            raise ValueError("base must have shape [num_nodes, hidden_dim]")
        if unseen_mask.shape != graph.node_kinds.shape or unseen_mask.dtype != torch.bool:
            raise ValueError("unseen_mask must be bool with one value per node")
        if unseen_mask.device != base.device:
            raise ValueError("unseen_mask and base must share a device")
        unseen_ids = torch.nonzero(unseen_mask, as_tuple=False).flatten()
        unseen_count = int(unseen_ids.numel())
        if unseen_count == 0:
            return base, FixedPointDiagnostics(True, 0, 0.0, 0)

        spectral_norm = torch.linalg.matrix_norm(self.message_weight, ord=2)
        weight = self.message_weight / spectral_norm.clamp_min(1.0)
        states = base
        src, dst = graph.edge_index[0], graph.edge_index[1]
        if dst.numel():
            degree = torch.bincount(dst, minlength=base.shape[0]).to(base.dtype).unsqueeze(-1)
        else:
            degree = base.new_zeros((base.shape[0], 1))
        degree = degree.clamp_min(1.0)
        relations = self.relation_embedding(graph.edge_types)
        unseen_base = base.index_select(0, unseen_ids)
        converged = False
        residual_value = float("inf")
        iterations = 0
        for step in range(1, self.max_iterations + 1):
            aggregate = torch.zeros_like(states)
            if src.numel():
                messages = F.linear(states.index_select(0, src), weight) + relations
                aggregate.index_add_(0, dst, messages)
                aggregate = aggregate / degree
            context = aggregate.index_select(0, unseen_ids)
            candidate = torch.tanh(unseen_base + context)
            unseen_updated = (1.0 - self.damping) * unseen_base + self.damping * candidate
            updated = states.index_copy(0, unseen_ids, unseen_updated)
            difference = unseen_updated - states.index_select(0, unseen_ids)
            residual = torch.linalg.vector_norm(difference, dim=-1).max()
            residual_value = float(residual.detach())
            states = updated
            iterations = step
            if residual_value <= self.tolerance:
                converged = True
                break
        return states, FixedPointDiagnostics(converged, iterations, residual_value, unseen_count)


class AttentionConvolutionLayer(nn.Module):
    """Relation-aware sparse multi-head attention convolution with GELU."""

    def __init__(self, num_relations: int) -> None:
        super().__init__()
        self.head_dim = HIDDEN_DIM // NUM_HEADS
        self.query = nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False)
        self.key = nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False)
        self.value = nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False)
        self.relation_key = nn.Embedding(num_relations, HIDDEN_DIM)
        self.relation_value = nn.Embedding(num_relations, HIDDEN_DIM)
        self.self_key = nn.Parameter(torch.zeros(NUM_HEADS, self.head_dim))
        self.self_value = nn.Parameter(torch.zeros(NUM_HEADS, self.head_dim))
        self.output = nn.Linear(HIDDEN_DIM, HIDDEN_DIM)
        self.norm_attention = nn.LayerNorm(HIDDEN_DIM)
        self.feed_forward = nn.Sequential(
            nn.Linear(HIDDEN_DIM, HIDDEN_DIM * 2),
            nn.GELU(),
            nn.Linear(HIDDEN_DIM * 2, HIDDEN_DIM),
        )
        self.norm_feed_forward = nn.LayerNorm(HIDDEN_DIM)

    def forward(self, nodes: Tensor, graph: ExprGraph) -> Tensor:
        n = nodes.shape[0]
        if n == 0:
            return nodes
        q = self.query(nodes).view(n, NUM_HEADS, self.head_dim)
        k = self.key(nodes).view(n, NUM_HEADS, self.head_dim)
        v = self.value(nodes).view(n, NUM_HEADS, self.head_dim)
        real_src, real_dst = graph.edge_index[0], graph.edge_index[1]
        self_nodes = torch.arange(n, device=nodes.device, dtype=torch.long)
        src = torch.cat((real_src, self_nodes))
        dst = torch.cat((real_dst, self_nodes))
        edge_k = torch.cat(
            (
                self.relation_key(graph.edge_types).view(-1, NUM_HEADS, self.head_dim),
                self.self_key.unsqueeze(0).expand(n, -1, -1),
            ),
            dim=0,
        )
        edge_v = torch.cat(
            (
                self.relation_value(graph.edge_types).view(-1, NUM_HEADS, self.head_dim),
                self.self_value.unsqueeze(0).expand(n, -1, -1),
            ),
            dim=0,
        )
        scores = (q.index_select(0, dst) * (k.index_select(0, src) + edge_k)).sum(-1)
        scores = scores / (self.head_dim**0.5)
        messages = v.index_select(0, src) + edge_v

        destinations = dst.unsqueeze(-1).expand(-1, NUM_HEADS)
        maxima = scores.new_full((n, NUM_HEADS), float("-inf"))
        maxima.scatter_reduce_(0, destinations, scores.detach(), reduce="amax", include_self=True)
        weights = (scores - maxima.index_select(0, dst)).exp()
        denominators = weights.new_zeros((n, NUM_HEADS)).index_add(0, dst, weights)
        weights = weights / denominators.index_select(0, dst)
        aggregated = messages.new_zeros((n, NUM_HEADS, self.head_dim))
        aggregated = aggregated.index_add(0, dst, weights.unsqueeze(-1) * messages)
        combined = aggregated.reshape(n, HIDDEN_DIM)
        nodes = self.norm_attention(nodes + self.output(combined))
        return self.norm_feed_forward(nodes + self.feed_forward(nodes))


class PaperAlignedNPA(nn.Module):
    """32-dim, five-layer/four-head independent NPA-style graph model.

    `forward` returns Kind logits until a `TacticPrefix` is supplied. Thereafter
    it returns logits for exactly the next parameter in that Kind's sequence.
    Earlier argument values are validated but intentionally do not condition
    later heads, matching the paper's stated simplification. Candidate masks are
    applied as negative-infinity logits.
    """

    def __init__(self, num_constants: int, num_relations: int, node_feature_dim: int) -> None:
        super().__init__()
        if num_constants < 1 or num_relations < 1 or node_feature_dim < 1:
            raise ValueError("num_constants, num_relations, and node_feature_dim must be positive")
        self.num_constants = num_constants
        self.num_relations = num_relations
        self.node_feature_dim = node_feature_dim
        self.node_kind_embedding = nn.Embedding(len(NodeKind), HIDDEN_DIM)
        self.tactic_kind_embedding = nn.Embedding(len(TacticKind), HIDDEN_DIM)
        self.constant_embedding = nn.Embedding(num_constants, HIDDEN_DIM)
        self.feature_projection = nn.Linear(node_feature_dim, HIDDEN_DIM)
        self.unseen_constant_encoder = FixedPointConstantEncoder(num_relations)
        self.core = nn.ModuleList(AttentionConvolutionLayer(num_relations) for _ in range(NUM_LAYERS))
        self.empty_graph_embedding = nn.Parameter(torch.zeros(HIDDEN_DIM))
        self.kind_head = nn.Linear(HIDDEN_DIM, len(TacticKind))

        self.decoder_init = nn.Linear(HIDDEN_DIM * 2, HIDDEN_DIM)
        self.category_heads = nn.ModuleDict(
            {name: nn.Linear(HIDDEN_DIM, len(values)) for name, values in CATEGORY_VALUES.items()}
        )
        self.pointer_query = nn.ModuleDict(
            {name: nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False) for name in POINTER_PARAMETERS}
        )
        self.pointer_key = nn.ModuleDict(
            {name: nn.Linear(HIDDEN_DIM, HIDDEN_DIM, bias=False) for name in POINTER_PARAMETERS}
        )

    def _validate_graph(self, graph: ExprGraph) -> None:
        graph.validate(self.node_feature_dim)
        if graph.node_kinds.numel():
            if int(graph.node_kinds.min()) < 0 or int(graph.node_kinds.max()) >= len(NodeKind):
                raise ValueError("node_kinds contains an unknown NodeKind ID")
            if int(graph.constant_ids.min()) < -1:
                raise ValueError("constant_ids must be -1 or a nonnegative vocabulary ID")
            is_constant = graph.node_kinds == int(NodeKind.CONST)
            if bool(((graph.constant_ids >= 0) & ~is_constant).any()):
                raise ValueError("only CONST nodes may have a known constant ID")
            if bool((graph.constant_ids[is_constant] >= self.num_constants).any()):
                raise ValueError("constant ID exceeds model vocabulary")
        if graph.edge_types.numel() and (int(graph.edge_types.min()) < 0 or int(graph.edge_types.max()) >= self.num_relations):
            raise ValueError("edge_types contains a relation ID outside the model vocabulary")

    def _initial_nodes(self, graph: ExprGraph) -> tuple[Tensor, FixedPointDiagnostics]:
        nodes = self.feature_projection(graph.node_features) + self.node_kind_embedding(graph.node_kinds)
        known_constants = (graph.node_kinds == int(NodeKind.CONST)) & (graph.constant_ids >= 0)
        if bool(known_constants.any()):
            nodes = nodes.clone()
            nodes[known_constants] = nodes[known_constants] + self.constant_embedding(
                graph.constant_ids[known_constants]
            )
        unseen = (graph.node_kinds == int(NodeKind.CONST)) & (graph.constant_ids == -1)
        return self.unseen_constant_encoder(nodes, graph, unseen)

    def _decode_parameter(
        self,
        name: str,
        state: Tensor,
        nodes: Tensor,
        candidates: Optional[CandidateSet],
    ) -> Tensor:
        if name in POINTER_PARAMETERS:
            if candidates is None:
                raise ValueError(f"CandidateSet is required for pointer parameter {name!r}")
            choices = candidates.for_parameter(name)
            if name == "premise":
                choices.validate(self.num_constants, self.constant_embedding.weight.device)
                choice_ids = choices.constant_ids
                choice_embeddings = self.constant_embedding(choice_ids)
            else:
                choices.validate(nodes.shape[0], nodes.device)
                choice_ids = choices.indices
                choice_embeddings = nodes.index_select(0, choice_ids)
            if choice_ids.numel() == 0 or not bool(choices.mask.any()):
                raise ValueError(f"pointer parameter {name!r} has no eligible candidates")
            query = self.pointer_query[name](state)
            keys = self.pointer_key[name](choice_embeddings)
            logits = keys @ query / (HIDDEN_DIM**0.5)
            return logits.masked_fill(~choices.mask, float("-inf"))
        return self.category_heads[name](state)

    def _validate_selected(
        self,
        name: str,
        value: int,
        nodes: Tensor,
        candidates: Optional[CandidateSet],
    ) -> None:
        if name in POINTER_PARAMETERS:
            if candidates is None:
                raise ValueError(f"CandidateSet is required for selected pointer {name!r}")
            choices = candidates.for_parameter(name)
            if name == "premise":
                choices.validate(self.num_constants, self.constant_embedding.weight.device)
                matches = torch.nonzero((choices.constant_ids == value) & choices.mask, as_tuple=False).flatten()
                if matches.numel() != 1:
                    raise ValueError("selected premise ID must be exactly one eligible candidate")
            else:
                choices.validate(nodes.shape[0], nodes.device)
                matches = torch.nonzero((choices.indices == value) & choices.mask, as_tuple=False).flatten()
                if matches.numel() != 1:
                    raise ValueError(f"selected {name} node must be exactly one eligible candidate")
            return
        vocab = CATEGORY_VALUES[name]
        if value < 0 or value >= len(vocab):
            raise ValueError(f"selected {name} class is outside its categorical vocabulary")

    def _encode(
        self, graph: ExprGraph
    ) -> tuple[Tensor, Tensor, Tensor, FixedPointDiagnostics]:
        """Run the graph encoder and Kind head once for a state."""
        self._validate_graph(graph)
        nodes, fixed_point = self._initial_nodes(graph)
        for layer in self.core:
            nodes = layer(nodes, graph)
        pooled = nodes.mean(dim=0) if nodes.shape[0] else self.empty_graph_embedding
        kind_logits = self.kind_head(pooled)
        return nodes, pooled, kind_logits, fixed_point

    def _decoder_state(self, pooled: Tensor, kind: TacticKind) -> Tensor:
        return torch.tanh(
            self.decoder_init(
                torch.cat((pooled, self.tactic_kind_embedding.weight[int(kind)]))
            )
        )

    def _validated_prefix(
        self,
        prefix: TacticPrefix,
        nodes: Tensor,
        candidates: Optional[CandidateSet],
    ) -> tuple[TacticKind, tuple[str, ...], list[str]]:
        try:
            kind = TacticKind(prefix.kind)
        except ValueError as exc:
            raise ValueError("prefix.kind is not a valid TacticKind") from exc
        sequence = TACTIC_PARAMETERS[kind]
        selected_names = list(prefix.selected.keys())
        if len(selected_names) > len(sequence):
            raise ValueError("selected parameter prefix is longer than the tactic parameter sequence")
        if selected_names != list(sequence[: len(selected_names)]):
            raise ValueError("selected parameters must be a contiguous prefix in tactic order")
        for name in selected_names:
            self._validate_selected(name, int(prefix.selected[name]), nodes, candidates)
        return kind, sequence, selected_names

    def forward(
        self,
        graph: ExprGraph,
        candidates: Optional[CandidateSet] = None,
        prefix: Optional[TacticPrefix] = None,
    ) -> NPAOutput:
        """Kind logits, or logits for the next parameter of a selected prefix.

        This is the original single-step interface and remains the inference
        API.  For teacher-forced multi-parameter training use
        :meth:`forward_prefix` or :meth:`parameter_logits`, which compute all
        Kind-dependent heads in one graph pass.
        """

        nodes, pooled, kind_logits, fixed_point = self._encode(graph)
        if prefix is None:
            return NPAOutput(nodes, pooled, kind_logits, None, None, None, fixed_point)
        kind, sequence, selected_names = self._validated_prefix(prefix, nodes, candidates)
        state = self._decoder_state(pooled, kind)
        if len(selected_names) == len(sequence):
            return NPAOutput(nodes, pooled, kind_logits, None, None, state, fixed_point)
        next_parameter = sequence[len(selected_names)]
        logits = self._decode_parameter(next_parameter, state, nodes, candidates)
        return NPAOutput(nodes, pooled, kind_logits, next_parameter, logits, state, fixed_point)

    def forward_prefix(
        self,
        graph: ExprGraph,
        candidates: Optional[CandidateSet],
        prefix: TacticPrefix | TacticKind,
        parameters: Optional[Iterable[str]] = None,
    ) -> NPAPrefixOutput:
        """Return logits for several (or all) parameter heads of one Kind.

        `prefix` contributes the Kind and a validated contiguous selection; its
        selected values do not change any logits.  `parameters` selects which
        heads to decode (default: the full Kind sequence).  This lets a trainer
        skip unlabeled heads without requiring irrelevant candidate sets.
        Pointer heads still raise when their candidate list is empty or fully
        masked.
        """

        if isinstance(prefix, TacticKind):
            prefix = TacticPrefix(prefix)
        kind = prefix.kind
        nodes, pooled, kind_logits, fixed_point = self._encode(graph)
        kind, sequence, _ = self._validated_prefix(prefix, nodes, candidates)
        if parameters is None:
            requested = list(sequence)
        else:
            requested = list(parameters)
            if len(set(requested)) != len(requested):
                raise ValueError("requested parameters must be unique")
            unknown = [name for name in requested if name not in sequence]
            if unknown:
                raise ValueError(
                    f"parameters {unknown!r} are not in the sequence for {kind.name}"
                )
            requested = [name for name in sequence if name in set(requested)]
        state = self._decoder_state(pooled, kind)
        parameter_logits = {
            name: self._decode_parameter(name, state, nodes, candidates)
            for name in requested
        }
        return NPAPrefixOutput(
            node_embeddings=nodes,
            pooled_embedding=pooled,
            kind_logits=kind_logits,
            parameter_logits=parameter_logits,
            decoder_state=state,
            fixed_point=fixed_point,
            kind=kind,
            selected=dict(prefix.selected),
        )

    def parameter_logits(
        self,
        graph: ExprGraph,
        candidates: Optional[CandidateSet],
        kind: TacticKind | str,
        parameters: Optional[Iterable[str]] = None,
    ) -> dict[str, Tensor]:
        """Convenience wrapper around :meth:`forward_prefix` for a bare Kind."""

        if isinstance(kind, str):
            kind = tactic_kind_from_name(kind)
        return dict(
            self.forward_prefix(
                graph,
                candidates,
                TacticPrefix(kind),
                parameters=parameters,
            ).parameter_logits
        )
