@dataclass(frozen=True)
class ParameterSpec:
    """Static description of one Kind-dependent parameter head.

    Pointer heads score a caller-supplied candidate list.  Categorical heads
    score a fixed class vocabulary.  `mask` documents the eligibility contract;
    every pointer head applies its bool mask as negative-infinity logits and
    raises when no eligible candidate remains.
    """

    name: str
    kind: str
    candidate_source: str
    mask: str


