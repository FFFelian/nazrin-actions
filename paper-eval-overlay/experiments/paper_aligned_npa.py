"""
Independent, paper-aligned NPA model skeleton for typed expression graphs.

This is not an exact reproduction: the paper specifies 32-dimensional node
representations, a five-layer/four-head attention-convolution GNN, GELU, and
Kind-dependent NPA argument heads. Its conclusion states that later arguments
are not conditioned on earlier argument values; this module follows that rule.
The paper does not provide complete update equations or executable code. The
contractive fixed-point operator, attention details, graph readout, and concrete
tactic/parameter vocabularies here are independent implementation choices.

The caller must provide essentialized graphs, eligible candidate sets, and
structured labels. ExprGraph is only a tensor interface: it does not itself
establish alpha equivalence, shared constants/loci, or coupled-goal semantics.
The fixed-point encoder operates on the supplied graph context; a definition-
graph encoder for stable embeddings of globally unseen premises is not yet
implemented. This module does not train on trace-proxy data, which has neither
ExprGraph inputs nor parameter labels.

`TacticKind` was extended from the original placeholder set to the atomic
tactic schema in `Nazrin/Contextualization.lean`.  `PARAMETER_SPECS` documents
the candidate source and mask for every Kind-dependent parameter head.
`define`/`have`/`let`/`raw` map to `OTHER` in this version because their
binder-name/value/type/raw-string payloads are not representable by the current
pointer/categorical heads; see `experiments/npa_training/README.md`.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import IntEnum
from typing import Iterable, Mapping, Optional

